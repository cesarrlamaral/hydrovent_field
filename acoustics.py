# 1. Propriedades acústicas da água do mar
# --------------------------------------------------------------------------

def sound_speed_seawater(temp_c: float, depth_m: float, salinity_psu: float = 34.7) -> float:
    """
    Velocidade do som na água do mar — equação de nove termos de
    Mackenzie, K.V. (1981), "Nine-term equation for sound speed in the
    oceans," J. Acoust. Soc. Am. 70(3), 807-812 (verificado por leitura
    direta do PDF primário completo, 2026-08-08: os 9 coeficientes batem
    exatamente com a eq. (1) do artigo). Válida para T=-2 a 30°C, S=25-40
    psu, D=0-8000 m — cobre com folga as condições ambientes deste
    projeto (T=2°C, D~2000-3000m).
    """
    t, s, d = temp_c, salinity_psu, depth_m
    return (
        1448.96 + 4.591 * t - 5.304e-2 * t**2 + 2.374e-4 * t**3
        + 1.340 * (s - 35) + 1.630e-2 * d + 1.675e-7 * d**2
        - 1.025e-2 * t * (s - 35) - 7.139e-13 * t * d**3
    )


def seawater_absorption_np_per_m(freq_hz: float, temp_c: float, depth_m: float,
                                  salinity_psu: float = 34.7, ph: float = 7.8) -> float:
    """
    Coeficiente de absorção acústica da água do mar, convertido para
    Np/m. Fórmula simplificada de Ainslie, M.A., & McColm, J.G. (1998),
    "A simplified formula for viscous and chemical absorption in sea
    water," J. Acoust. Soc. Am. 103(3), 1671-1672 (relaxação de ácido
    bórico + MgSO4 + viscosidade da água pura).

    Nas frequências de interesse aqui (10-500 Hz, banda medida por Crone
    et al. 2006), o resultado é da ordem de 1e-3 dB/km — desprezível ao
    longo da escala do domínio simulado (centenas a ~1 km): por isso o
    termo é calculado e aplicado (não simplesmente omitido), mas o efeito
    numérico é, de fato, mínimo. Ver tests/test_acoustics.py para o
    valor de referência.
    """
    f_khz = freq_hz / 1000.0
    d_km = depth_m / 1000.0
    t, s = temp_c, salinity_psu

    f1 = 0.78 * math.sqrt(s / 35.0) * math.exp(t / 26.0)
    f2 = 42.0 * math.exp(t / 17.0)

    term_boric = 0.106 * (f1 * f_khz**2) / (f1**2 + f_khz**2) * math.exp((ph - 8.0) / 0.56)
    term_mgso4 = (0.52 * (1 + t / 43.0) * (s / 35.0) * (f2 * f_khz**2) / (f2**2 + f_khz**2)
                  * math.exp(-d_km / 6.0))
    term_water = 0.00049 * f_khz**2 * math.exp(-(t / 27.0 + d_km / 17.0))

    alpha_db_per_km = term_boric + term_mgso4 + term_water
    return alpha_db_per_km / 8.686 / 1000.0  # dB/km -> Np/m


