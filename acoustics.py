"""
Modelo acústico exploratório: concentração de moléculas prebióticas via
campo sonoro gerado por fumarolas hidrotermais (Fase 2 do projeto).

HIPÓTESE TESTADA (formulação do usuário): o campo acústico real gerado
por fumarolas hidrotermais pode transportar/concentrar moléculas
prebióticas em regiões de interferência das ondas que se propagam nesse
campo. Nenhuma publicação encontrada na pesquisa que fundamenta este
módulo propõe esse mecanismo para vents hidrotermais — é uma hipótese
original, não uma implementação de um modelo já publicado. Ver seção
"Limitações" em docs/PHYSICS_MODEL.md antes de citar qualquer resultado
deste módulo.

Fonte acústica real (não hipotética): Crone, T.J., Wilcock, W.S.D.,
Barclay, A.H., & Parsons, J.D. (2006). "The Sound Generated by
Mid-Ocean Ridge Black Smoker Hydrothermal Vents." PLOS ONE 1(1): e133.
Vents "Sully" e "Puffer" (Endeavour, Juan de Fuca) medidos: sinal de
banda larga 5-500 Hz (10-30 dB acima do ruído ambiente), tons estreitos
10-250 Hz (largura 5-15 Hz, 10-20 dB acima da banda larga), pressão RMS
0.4-2.6 Pa. Mecanismos propostos por Crone et al.: fluxo pulsante
(monopolo no orifício), mistura turbulenta (dipolo), interação
fluido-estrutura na chaminé, ressonância tipo Helmholtz/quarto-de-onda
na própria chaminé.

PROBLEMA FÍSICO CENTRAL identificado antes de implementar (ver
conversa que motivou este módulo): a força de radiação acústica clássica
(potencial de Gor'kov) escala com o volume da partícula (∝r³) e não tem
efeito demonstrado sobre moléculas livres dissolvidas (sub-nm a poucos
nm) — só é eficaz a partir de ~1 μm. "Moléculas presas diretamente em
nós de interferência" não é defensável com a acustofluídica conhecida.
Este módulo por isso implementa DOIS mecanismos fisicamente distintos e
deixa o usuário escolher (`mode`):

- "streaming": streaming acústico (fluxo secundário de contorno,
  Rayleigh/Nyborg) advecta e retém SOLUTO DISSOLVIDO de fato — o
  mecanismo correto para moléculas livres, independente de tamanho.
  Implementado resolvendo a equação de advecção-difusão estacionária
  real (não uma fórmula heurística) com e sem o campo de streaming, e
  comparando as duas soluções (mesmo padrão de controle usado em
  prebiotic.py).
- "particle_trap": armadilha de partícula via potencial de Gor'kov
  (colóide mineral de sulfeto, >1 μm, dentro do regime onde a força de
  radiação de fato funciona); a concentração MOLECULAR é assumida
  proporcional à concentração local de partícula (aproximação
  documentada — ver docs/PHYSICS_MODEL.md).
- "both": os dois mecanismos compostos multiplicativamente.

Interferência coerente vs. incoerente ENTRE vents diferentes
(`cross_vent_coherence`, ver `compute_acoustic_field`): não há evidência
de sincronismo de fase entre fumarolas independentes (Crone et al. só
reportam modulação de AMPLITUDE por maré, não travamento de fase), e as
linhas tonais têm banda finita (5-15 Hz) implicando tempo de coerência
curto (~dezenas de ms) — franjas de interferência ENTRE vents
diferentes não seriam estáveis no tempo. Por isso o modo padrão
("incoherent") modela apenas a auto-interferência de CADA fumarola com
sua própria imagem refletida no fundo local (fonte + espelho, mesma
fonte, geometria fixa = sempre coerente e estável, independente de
qualquer suposição de fase entre vents) — e soma os campos de
diferentes vents em POTÊNCIA (incoerente). Isso ainda produz uma
estrutura espacial real de nós/antinós (franjas), só que ancorada em
cada fumarola individualmente, não em batimentos entre fumarolas
distintas.

Essa é uma suposição por AUSÊNCIA de evidência (Crone et al. 2006 não
mede coerência de fase entre vents vizinhos), não uma medição que
descarta o cenário oposto. Um cenário fisicamente plausível de
coerência parcial existe: vents do mesmo cluster, com chaminés de
altura semelhante, poderiam ter frequências de ressonância tonal
próximas e ficar parcialmente travados em fase. Para testar se essa
suposição importa para a conclusão do modelo, `cross_vent_coherence`
também aceita "coherent": um cenário deliberadamente idealizado de
MELHOR CASO em que TODAS as fumarolas compartilham uma única frequência
tonal sorteada (em vez de uma por fumarola) e seus fasores de
pressão/velocidade são somados em fase, não em potência — um limite
superior otimista, não uma previsão realista, usado para delimitar
(bounding test) o quanto a suposição de incoerência afeta o resultado:
se mesmo esse limite otimista continuar fisicamente irrelevante (poço
de Gor'kov << kT), a conclusão de irrelevância do mecanismo fica mais
robusta; se o limite otimista cruzar o limiar, isso é um achado
específico e testável (preveria estrutura acústica de fundo diferente
entre clusters de altura de chaminé homogênea vs. heterogênea). O ruído
de banda larga (turbulência) nunca é somado coerentemente em nenhum dos
dois modos — coerência é um conceito de linha tonal, não de ruído de
banda larga.

CORREÇÃO (2026-08-06): antes desta versão, o termo de VELOCIDADE
(usado tanto pelo streaming de contorno quanto pelo potencial de
Gor'kov) somava os fasores complexos de velocidade de fumarolas
DIFERENTES antes de elevar ao quadrado — uma soma coerente de fato,
inconsistente com a soma em potência já usada (corretamente) para a
PRESSÃO, e sem sentido físico bem definido quando as fumarolas somadas
têm frequências tonais diferentes (fasores de frequências diferentes
não podem ser somados como um único fasor). Isso vazava uma forma de
interferência coerente ENTRE vents não documentada e não pretendida,
por um caminho diferente do da pressão. Corrigido: o termo de
velocidade agora segue exatamente a mesma escolha de
`cross_vent_coherence` que o termo de pressão (soma em potência por
padrão; soma em fase só no modo "coherent" explícito, com frequência
compartilhada).
"""

