@dataclass
class VentAcousticSource:
    vent_id: int
    x_m: float
    y_m: float
    floor_elev_m: float        # elevação local do fundo (relativa), usada como plano-espelho
    source_height_m: float     # altura do orifício acima do fundo local (~altura da chaminé)
    freq_hz: float              # frequência do tom estreito, amostrada empiricamente
    p_ref_broadband_pa: float   # pressão RMS de banda larga na distância de referência
    p_ref_tonal_pa: float       # pressão RMS do tom estreito na distância de referência


def build_acoustic_sources(vents: List["Vent"], terrain: np.ndarray, domain_size_m: float,
                            local_relief_m: float, rng: np.random.Generator,
                            cross_vent_coherence: str = "incoherent") -> List[VentAcousticSource]:
    """
    Constrói uma fonte acústica por fumarola. A frequência do tom NÃO é
    derivada da geometria da chaminé por uma fórmula mecanicista: Crone
    et al. (2006) propõem ressonância tipo Helmholtz/quarto-de-onda como
    UMA hipótese entre várias mecanismos possíveis, sem fornecer uma
    relação geometria->frequência fechada e verificada. Por isso a
    frequência é amostrada da faixa empiricamente observada (10-250 Hz),
    não calculada a partir de `chimney_height_m` — uma escolha
    deliberadamente mais honesta que fingir uma relação não estabelecida
    na fonte primária.

    `cross_vent_coherence="coherent"`: pré-condição física necessária
    para que fumarolas diferentes possam ter franjas de interferência
    estáveis entre si (ver docstring do módulo) — todas as fumarolas
    recebem a MESMA frequência tonal (sorteada uma única vez), em vez de
    uma frequência independente por fumarola. Cenário de melhor caso
    idealizado, não uma medição.
    """
    size = terrain.shape[0]
    meters_per_cell = domain_size_m / (size - 1)
    shared_freq_hz = float(rng.uniform(*TONAL_FREQ_RANGE_HZ)) if cross_vent_coherence == "coherent" else None
    sources = []
    for v in vents:
        xi, yi = int(np.clip(v.x, 0, size - 1)), int(np.clip(v.y, 0, size - 1))
        floor_elev_m = float(terrain[yi, xi] * local_relief_m)
        freq_hz = shared_freq_hz if shared_freq_hz is not None else float(rng.uniform(*TONAL_FREQ_RANGE_HZ))
        broadband_pa = float(rng.uniform(*BROADBAND_RMS_PA_RANGE))
        excess_db = float(rng.uniform(*TONAL_EXCESS_DB_RANGE))
        tonal_pa = broadband_pa * 10 ** (excess_db / 20.0)
        sources.append(VentAcousticSource(
            vent_id=v.id, x_m=v.x * meters_per_cell, y_m=v.y * meters_per_cell,
            floor_elev_m=floor_elev_m, source_height_m=max(v.chimney_height_m, 0.5),
            freq_hz=freq_hz, p_ref_broadband_pa=broadband_pa, p_ref_tonal_pa=tonal_pa,
        ))
    return sources


# --------------------------------------------------------------------------
# 3. Campo de pressão: auto-interferência fonte + imagem no fundo
# --------------------------------------------------------------------------

def _source_image_distances(source: VentAcousticSource, X: np.ndarray, Y: np.ndarray,
                             z_receiver: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    z_direct = source.floor_elev_m + source.source_height_m
    z_image = source.floor_elev_m - source.source_height_m
    r_direct = np.sqrt((X - source.x_m) ** 2 + (Y - source.y_m) ** 2 + (z_receiver - z_direct) ** 2)
    r_image = np.sqrt((X - source.x_m) ** 2 + (Y - source.y_m) ** 2 + (z_receiver - z_image) ** 2)
    floor = REFERENCE_DISTANCE_M * 0.5
    return np.maximum(r_direct, floor), np.maximum(r_image, floor)


def vent_tonal_pressure_phasor(source: VentAcousticSource, X: np.ndarray, Y: np.ndarray,
                                z_receiver: np.ndarray, c_sound: float,
                                alpha_np_per_m: float) -> np.ndarray:
    """
    Fasor complexo de pressão do tom estreito desta fumarola: soma
    COERENTE direto + imagem (mesma fonte, geometria fixa -> sempre
    válida, sem suposição de fase entre fumarolas). |resultado|^2 é a
    intensidade da onda estacionária de auto-interferência dessa
    fumarola sozinha — o efeito clássico do "espelho de Lloyd" (Lloyd's
    mirror; ver Urick, R.J., "Principles of Underwater Sound") aplicado
    a uma fumarola perto do fundo.

    Limitação de visibilidade de franjas, importante e não-óbvia: a
    diferença máxima de caminho fonte-vs-imagem é limitada a
    2×(altura do receptor) = 2×1m = 2m (receptor fixo a 1m do fundo,
    ver `receiver_height_m`), INDEPENDENTE da altura da chaminé. Nas
    frequências reais medidas por Crone et al. (2006) (10-250 Hz,
    λ=6-150m), essa diferença de caminho cobre MENOS de um ciclo
    completo de interferência (4×1m/λ < 1 para λ>4m) — ou seja, a
    auto-interferência de campo próximo real, nas condições deste
    modelo, aparece como um único realce/sombra suave perto da
    fumarola, não como múltiplos nós/antinós periódicos. Franjas
    múltiplas só aparecem para frequências bem mais altas que a faixa
    medida (ver tests/test_acoustics.py, onde 1000 Hz é usado
    deliberadamente para validar a matemática, não para representar a
    faixa real).
    """
    r_direct, r_image = _source_image_distances(source, X, Y, z_receiver)
    k = 2 * np.pi * source.freq_hz / c_sound
    amp_direct = source.p_ref_tonal_pa * REFERENCE_DISTANCE_M / r_direct * np.exp(-alpha_np_per_m * r_direct)
    amp_image = source.p_ref_tonal_pa * REFERENCE_DISTANCE_M / r_image * np.exp(-alpha_np_per_m * r_image)
    return amp_direct * np.exp(1j * k * r_direct) + BOTTOM_REFLECTION_COEFF * amp_image * np.exp(1j * k * r_image)


def vent_broadband_pressure_rms(source: VentAcousticSource, X: np.ndarray, Y: np.ndarray,
                                 z_receiver: np.ndarray, alpha_np_per_m: float) -> np.ndarray:
    """
    Componente de banda larga: turbulência de fluxo, sem relação de fase
    fixa através da banda (5-500 Hz) -> a interferência fina entre
    direto/imagem se borra ao integrar sobre a banda. Soma-se em
    potência (incoerente), não em fase.
    """
    r_direct, r_image = _source_image_distances(source, X, Y, z_receiver)
    amp_direct = source.p_ref_broadband_pa * REFERENCE_DISTANCE_M / r_direct * np.exp(-alpha_np_per_m * r_direct)
    amp_image = source.p_ref_broadband_pa * REFERENCE_DISTANCE_M / r_image * np.exp(-alpha_np_per_m * r_image)
    return np.sqrt(amp_direct ** 2 + (BOTTOM_REFLECTION_COEFF * amp_image) ** 2)


def _particle_velocity_from_pressure(p_phasor: np.ndarray, meters_per_cell: float,
                                      omega: float, rho: float) -> Tuple[np.ndarray, np.ndarray]:
    """
    Velocidade de partícula acústica (componentes horizontais) a partir
    da equação de momento linearizada: -iωρv = -∇p => v = ∇p/(iωρ).
    Relação GERAL (campo próximo ou distante), preferida aqui sobre o
    atalho de campo distante v≈p/(ρc) porque este último apagaria
    exatamente a separação nó-de-pressão/antinó-de-velocidade da onda
    estacionária de auto-interferência — que é o efeito físico central
    de que depende o mecanismo de aprisionamento (módulo Gor'kov,
    seção 5). Só as componentes horizontais são resolvidas (campo
    avaliado num plano horizontal fixo, ver seção 4) — a componente
    vertical não é modelada, limitação documentada.
    """
    dpdy, dpdx = np.gradient(p_phasor, meters_per_cell, meters_per_cell)
    denom = 1j * omega * rho
    return dpdx / denom, dpdy / denom


