def sample_field_at_vents(field_grid: np.ndarray, vents: List["Vent"]) -> Dict[int, float]:
    """Amostra o campo (índices de grade = posição x,y da fumarola) por vizinho mais próximo."""
    size = field_grid.shape[0]
    out = {}
    for v in vents:
        xi = int(np.clip(round(v.x), 0, size - 1))
        yi = int(np.clip(round(v.y), 0, size - 1))
        out[v.id] = float(field_grid[yi, xi])
    return out


def find_field_peaks(field_grid: np.ndarray, X: np.ndarray, Y: np.ndarray, top_n: int = 10,
                      neighborhood_cells: int = 5) -> List[dict]:
    """Detecta máximos locais do campo (filtro de máximo local) e devolve os `top_n` mais altos, em metros."""
    local_max = maximum_filter(field_grid, size=neighborhood_cells) == field_grid
    ys, xs = np.where(local_max)
    values = field_grid[ys, xs]
    order = np.argsort(values)[::-1][:top_n]
    return [
        {"x_m": float(X[ys[i], xs[i]]), "y_m": float(Y[ys[i], xs[i]]), "enrichment": float(values[i])}
        for i in order
    ]


def acoustic_enrichment_field(vents: List["Vent"], terrain: np.ndarray, domain_size_m: float,
                               local_relief_m: float, ocean_depth_baseline_m: float,
                               mode: str, rng: np.random.Generator,
                               ambient_temp_c: float = AMBIENT_TEMP_C_DEFAULT,
                               salinity_psu: float = 34.7, ph: float = 7.8,
                               particle_radius_m: Optional[float] = None,
                               particle_density_kg_m3: Optional[float] = None,
                               aggregate_radius_m: Optional[float] = None,
                               aggregate_density_kg_m3: Optional[float] = None,
                               cross_vent_coherence: str = "incoherent",
                               ) -> dict:
    """
    Ponto de entrada único do módulo acústico. `mode` em
    {"streaming","particle_trap","both"} ("off" nunca deve chegar aqui —
    filtrado pelo chamador). Retorna um dict com o campo final de
    enriquecimento (para visualização/detecção de picos), o fator por
    fumarola (para os módulos de prebiotic.py) e diagnósticos honestos
    sobre a plausibilidade física de cada mecanismo nas condições
    simuladas.

    `cross_vent_coherence` ("incoherent" padrão | "coherent"): ver
    docstring do módulo e de `compute_acoustic_field` — "coherent" é um
    limite superior idealizado (todas as fumarolas em uma única
    frequência compartilhada, somadas em fase), usado para testar se a
    suposição de incoerência entre fumarolas (a escolha fisicamente
    motivada, mas não medida diretamente) afeta a conclusão do modelo.

    `particle_radius_m`/`particle_density_kg_m3`: se AMBOS omitidos
    (padrão), o modo particle_trap/both usa a POPULAÇÃO de duas classes
    ancoradas em literatura (`PARTICLE_CLASSES` — colóide fino vs.
    agregado de campo próximo, ver docs/PHYSICS_MODEL.md), reportando
    diagnósticos para as duas e usando a classe mais favorável
    (`PRIMARY_PARTICLE_CLASS`) como campo principal. Se fornecidos
    explicitamente, usa esse ÚNICO tamanho customizado em vez da
    população citada (modo de exploração, ex.: "que tamanho seria
    necessário para a armadilha ficar relevante?").

    `aggregate_radius_m`/`aggregate_density_kg_m3`: só têm efeito
    quando a população citada está ativa (parâmetros acima omitidos) —
    sobrescrevem APENAS a classe `PRIMARY_PARTICLE_CLASS` (agregado),
    mantendo o colóide fino fixo. Usado pela varredura de sensibilidade
    (`--sensitivity-sweep` em fumarola_field.py) para amostrar dentro da
    faixa documentada 14-20 μm / 2400-3600 kg/m³ (González-Santana et
    al., 2020) em vez de fixar no ponto médio.
    """
    if mode not in ("streaming", "particle_trap", "both"):
        raise ValueError(f"modo acústico inválido: {mode!r}")

    field = compute_acoustic_field(vents, terrain, domain_size_m, local_relief_m,
                                    ocean_depth_baseline_m, ambient_temp_c, salinity_psu, ph, rng,
                                    cross_vent_coherence=cross_vent_coherence)

    diagnostics = {
        "sound_speed_m_s": field.sound_speed_m_s,
        "absorption_np_per_m_at_100hz": field.absorption_np_per_m_at_100hz,
        "cross_vent_coherence": cross_vent_coherence,
    }

    enrichment_streaming = enrichment_particle = None
    speed_max = depth_over_kt = None

    if mode in ("streaming", "both"):
        enrichment_streaming, speed_max = streaming_enrichment_field(field, vents, domain_size_m)
        diagnostics["streaming_speed_max_m_s"] = speed_max

    if mode in ("particle_trap", "both"):
        if particle_radius_m is not None and particle_density_kg_m3 is not None:
            u_field = gorkov_potential_field(field, particle_radius_m, particle_density_kg_m3)
            enrichment_particle, depth_over_kt = particle_boltzmann_enhancement(u_field, ambient_temp_c)
            diagnostics["gorkov_trap_depth_over_kT"] = depth_over_kt
            diagnostics["gorkov_trap_physically_relevant"] = bool(depth_over_kt is not None and depth_over_kt > 1.0)
            diagnostics["particle_classes"] = None
        else:
            class_results = {}
            for key, spec in PARTICLE_CLASSES.items():
                r = spec["radius_m"]
                rho = spec["density_kg_m3"]
                if key == PRIMARY_PARTICLE_CLASS:
                    r = aggregate_radius_m if aggregate_radius_m is not None else r
                    rho = aggregate_density_kg_m3 if aggregate_density_kg_m3 is not None else rho
                u_field_c = gorkov_potential_field(field, r, rho)
                enrich_c, depth_c = particle_boltzmann_enhancement(u_field_c, ambient_temp_c)
                class_results[key] = {
                    "radius_um": r * 1e6,
                    "density_kg_m3": rho,
                    "trap_depth_over_kT": depth_c,
                    "physically_relevant": bool(depth_c > 1.0),
                    "_field": enrich_c,
                }
            diagnostics["particle_classes"] = {
                k: {kk: vv for kk, vv in v.items() if kk != "_field"} for k, v in class_results.items()
            }
            primary = class_results[PRIMARY_PARTICLE_CLASS]
            enrichment_particle = primary["_field"]
            depth_over_kt = primary["trap_depth_over_kT"]
            diagnostics["gorkov_trap_depth_over_kT"] = depth_over_kt
            diagnostics["gorkov_trap_physically_relevant"] = primary["physically_relevant"]

    if mode == "streaming":
        combined = enrichment_streaming
    elif mode == "particle_trap":
        combined = enrichment_particle
    else:
        combined = enrichment_streaming * enrichment_particle

    per_vent_factor = sample_field_at_vents(combined, vents)
    peaks = find_field_peaks(combined, field.X, field.Y, top_n=10)

    return {
        "mode": mode,
        "X_m": field.X,
        "Y_m": field.Y,
        "enrichment_field": combined,
        "per_vent_factor": per_vent_factor,
        "peaks": peaks,
        "diagnostics": diagnostics,
    }
